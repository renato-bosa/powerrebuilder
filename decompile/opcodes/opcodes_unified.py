def get_opcode_name(opcode: int) -> str:
    """Get the name of an opcode."""
    info = OPCODES.get(opcode)
    return info.name if info else f"UNKNOWN_{opcode:02X}"

def get_opcode_length(opcode: int) -> int:
    """Get the length of an opcode instruction."""
    info = OPCODES.get(opcode)
    return info.length if info else 1

